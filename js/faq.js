/** Витягує з відповіді короткий уривок навколо знайденого слова. */
function highlight(text, q) {
    if (!q) return escapeHtml(text);
    const i = text.toLowerCase().indexOf(q);
    if (i < 0) return escapeHtml(text);
    return escapeHtml(text.slice(0, i))
        + '<mark>' + escapeHtml(text.slice(i, i + q.length)) + '</mark>'
        + escapeHtml(text.slice(i + q.length));
}

function matches(item, q) {
    if (!q) return true;
    return (item.q + ' ' + item.a + ' ' + item.ref).toLowerCase().includes(q);
}

export function renderFaq(queryText = '') {
    const q = queryText.trim().toLowerCase();
    const groups = FAQ
        .map(g => ({ ...g, items: g.items.filter(i => matches(i, q)) }))
        .filter(g => g.items.length);

    if (!groups.length) {
        return `<p class="list-empty">Нічого не знайдено.<br>
            Спробуйте інше слово — наприклад, «внески», «збори» або «борг».</p>`;
    }

    return groups.map(g => `
        <div class="faq-group">
            <h3 class="faq-group-title">${escapeHtml(g.group)}</h3>
            ${g.items.map(item => `
                <div class="faq-item">
                    <button type="button" class="faq-q">
                        <span class="faq-q-text">${highlight(item.q, q)}</span>
                        <svg class="faq-chevron" viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2"><polyline points="9 18 15 12 9 6"></polyline></svg>
                    </button>
                    <div class="faq-a" hidden>
                        <p class="faq-a-text">${highlight(item.a, q)}</p>
                        <span class="faq-ref">Статут, ${escapeHtml(item.ref)}</span>
                    </div>
                </div>`).join('')}
        </div>`).join('');
}

function wire(host) {
    host.querySelectorAll('.faq-q').forEach(btn => {
        btn.addEventListener('click', () => {
            const item = btn.closest('.faq-item');
            const body = item.querySelector('.faq-a');
            body.hidden = !body.hidden;
            item.classList.toggle('faq-open', !body.hidden);
        });
    });
}

export function loadFaq() {
    const host = document.getElementById('faqContainer');
    if (!host) return;
    const input = document.getElementById('faqSearch');
    if (input) input.value = '';
    host.innerHTML = renderFaq('');
    wire(host);

    const total = FAQ.reduce((s, g) => s + g.items.length, 0);
    const count = document.getElementById('faqCount');
    if (count) count.textContent = `${total} питань за Статутом`;
}

